export interface LitmusHit {
  rule: LitmusRule;
  matches: string[];
}

export interface LitmusResult {
  hits: LitmusHit[];
  segments: { text: string; level?: Level }[];
  score: "clean" | "medium" | "high";
}

export function checkClaim(input: string): LitmusResult {
  const text = input.slice(0, 600);
  const hits: LitmusHit[] = [];
  const ranges: { start: number; end: number; level: Level }[] = [];

  for (const rule of RULES) {
    const matches: string[] = [];
    for (const m of text.matchAll(rule.pattern)) {
      if (!m[0].trim()) continue;
      matches.push(m[0]);
      ranges.push({ start: m.index ?? 0, end: (m.index ?? 0) + m[0].length, level: rule.level });
    }
    if (matches.length) hits.push({ rule, matches });
  }

  // Сегменты для подсветки: high перекрывает medium.
  const marks: (Level | undefined)[] = Array.from({ length: text.length }, () => undefined);
  for (const r of ranges) {
    for (let i = r.start; i < r.end; i++) if (marks[i] !== "high") marks[i] = r.level;
  }
  const segments: { text: string; level?: Level }[] = [];
  for (let i = 0; i < text.length; i++) {
    const last = segments[segments.length - 1];
    if (last && last.level === marks[i]) last.text += text[i];
    else segments.push({ text: text[i]!, level: marks[i] });
  }

  const score = hits.some((h) => h.rule.level === "high") ? "high" : hits.length ? "medium" : "clean";
  return { hits, segments, score };
}
