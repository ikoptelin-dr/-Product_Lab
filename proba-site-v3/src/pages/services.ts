type QA = { q: string; a: string };
interface Svc {
  path: string;
  nav: NavKey;
  name: string;
  serviceType: string;
  title: string;
  description: string;
  h1: string;
  hero: Parameters<typeof pageHero>[0];
  body: string;
  faq?: QA[];
}

/** Строка «Цены: от X ₽» в первом экране — минимальная цена блока из site-prices.json (блок = направление) + ссылка на ceny.html. */
const priceLine = (block: string, id: string) =>
  `<p class="hero-note">Цены: от ${rub(blockFrom(block))}\u00a0₽ · <a href="ceny.html#${id}">Все цены</a></p>`;

function page(s: Svc): PageDoc {
  const ld: object[] = [
    breadcrumbLd([{ name: "Proba Lab", path: "index.html" }, { name: s.name, path: s.path }]),
    serviceLd(s.h1, s.serviceType, s.description, s.path),
  ];
  if (s.faq) ld.push(faqLd(s.faq));
  return { path: s.path, title: s.title, description: s.description, nav: s.nav, ld, body: `${pageHero(s.hero)}\n<div class="light">\n${s.body}\n</div>` };
}

const crumbs = (name: string) => [{ name: "Proba Lab", href: "index.html" }, { name }];

/* ---------------- Компоненты ---------------- */
/** Ситуации «Когда нужно» — короткие утверждения сеткой. */
const situations = (items: string[]) =>
  `<ul class="situations">${items.map((x) => `<li class="reveal"><span class="sit-mark" aria-hidden="true"></span><p>${x}</p></li>`).join("")}</ul>`;

/** Карточки (стекло на светлом). */
const cards = (items: [string, string][], o: { numbered?: boolean } = {}) =>
  `<${o.numbered ? "ol" : "ul"} class="card-grid${o.numbered ? " is-numbered" : ""}">${items
    .map(([t, d], i) => `<li class="card glass-light reveal">${o.numbered ? `<span class="card-n" aria-hidden="true">${String(i + 1).padStart(2, "0")}</span>` : ""}<h3>${t}</h3><p>${d}</p></li>`)
    .join("")}</${o.numbered ? "ol" : "ul"}>`;

/** Строки «название — описание» (каналы). */
const rows = (items: [string, string][]) =>
  `<ul class="rows">${items.map(([t, d]) => `<li class="reveal"><h3>${t}</h3><p>${d}</p></li>`).join("")}</ul>`;

/** Блоки «Что нужно от вас», «Результат» и т. п. — в одной панели. */
const info = (blocks: { title?: string; html: string }[], id?: string) =>
  `<section${id ? ` id="${id}"` : ""} class="section info-section" aria-label="${blocks.map((b) => b.title ?? "").filter(Boolean).join(", ")}">
  <div class="container">
    <div class="info-panel glass-light reveal" style="--cols:${blocks.length}">
      ${blocks.map((b) => `<div class="info-block">${b.title ? `<h2 class="info-title">${b.title}</h2>` : ""}${b.html}</div>`).join("\n      ")}
    </div>
  </div>
</section>`;

