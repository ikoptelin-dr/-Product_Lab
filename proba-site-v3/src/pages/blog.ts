const LINK_RE = /\[\[([^|\]]+)\|([^\]]+)\]\]/g;

function renderArticle(a: Article): PageDoc {
  const path = `blog/${a.slug}.html`;
  const page = `blog/${a.slug}`;
  const tx = (raw: string, where: string) => factText(page, raw, where).replace(LINK_RE, '<a class="text-link" href="$2">$1</a>');
  const item = (x: Item) => (typeof x === "string" ? `<li>${tx(x, "list")}</li>` : `<li><b>${esc(x[0])}</b> ${tx(x[1], "list")}</li>`);
  const blocks = a.blocks
    .map(
      (b) => `<h2>${esc(b.h)}</h2>
      ${(b.p ?? []).map((p) => `<p>${tx(p, "p")}</p>`).join("\n      ")}
      ${b.list ? `<${b.ordered ? "ol" : "ul"}>${b.list.map(item).join("")}</${b.ordered ? "ol" : "ul"}>` : ""}
      ${(b.after ?? []).map((p) => `<p>${tx(p, "p")}</p>`).join("\n      ")}`,
    )
    .join("\n      ");
  const byline = `<p class="byline"><span>${AUTHOR.name}, ${AUTHOR.role}</span><span aria-hidden="true"> · </span><time datetime="${PUBLISHED.iso}">${PUBLISHED.text}</time></p>`;
  const hero = pageHero({
    crumbs: [{ name: "Proba Lab", href: "../index.html" }, { name: "Блог", href: "index.html" }, { name: a.h1 }],
    eyebrow: "Блог",
    h1: a.h1,
    lead: tx(a.lead, "lead"),
    ctas: [{ label: a.cta.label, href: a.cta.href }],
    extra: byline,
  });
  const body = `${hero}
<div class="light">
<section class="section" aria-label="Статья">
  <div class="container">
    <article class="prose article">
      ${blocks}
    </article>
  </div>
</section>
<section class="section" aria-labelledby="related-title">
  <div class="container">
    <h2 id="related-title" class="next-title">Связанные услуги</h2>
    <ul class="svc-grid">${a.related
      .map((r) => `<li class="reveal"><a class="svc-card glass-light" href="${r.href}"><span class="svc-title">${esc(r.label)}</span><span class="svc-text">${esc(r.text)}</span><span class="arrow" aria-hidden="true"></span></a></li>`)
      .join("")}</ul>
  </div>
</section>
<section class="section" aria-labelledby="cta-title">
  <div class="container">
    <div class="dark-card grain article-cta reveal">
      <div>
        <h2 id="cta-title" class="h2">${keepLast(esc(a.cta.label))}</h2>
        <p class="dark-card-text">${esc(a.cta.text)}</p>
      </div>
      <div class="hero-actions">
        <a class="btn btn-primary btn-lg" href="${a.cta.href}">${esc(a.cta.label)}</a>
        ${a.cta.second ? `<a class="btn btn-ghost btn-lg" href="${a.cta.second.href}">${esc(a.cta.second.label)}</a>` : ""}
      </div>
    </div>
  </div>
</section>
</div>`;
  return {
    path,
    title: a.title,
    description: a.description,
    nav: "none",
    ld: [
      breadcrumbLd([
        { name: "Proba Lab", path: "index.html" },
        { name: "Блог", path: "blog/index.html" },
        { name: a.h1, path },
      ]),
      {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        headline: a.h1,
        description: a.description,
        inLanguage: "ru",
        datePublished: PUBLISHED.iso,
        dateModified: PUBLISHED.iso,
        author: { "@type": "Person", name: AUTHOR.name, jobTitle: "Врач, основатель Proba Lab" },
        publisher: { "@type": "Organization", name: "Proba Lab" },
        mainEntityOfPage: absUrl(path),
      },
    ],
    body,
  };
}

