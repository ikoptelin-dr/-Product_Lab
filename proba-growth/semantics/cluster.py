KEEP = r"метрик|\bseo\b|\bсео\b|продвиж|интеграц|отказн|производственн\w* контрол|crm|битрикс"
SOFT_NOISE = {"Заказ товаров на сайтах (не разработка)", "Регистрация в другом смысле", "Спортпит: розница и потребители"}

def classify(k):
    for p, why in NOISE:
        if has(p, k) and not (why in SOFT_NOISE and has(KEEP, k)):
            return ("Нерелевантно", why, "—", "")
    topic = next((t for t, p in TOPICS if has(p, k)), "99 Прочее")
    if has(JOBS, k): return ("Нецелевой: работа и обучение", topic, "Вакансии/курсы", "")
    intent = next((i for i, p in INTENT if has(p, k)), "Широкий (смешанный)")
    if topic.startswith("99") and has(r"заказать|кредит|китай|сайт|сетев|штраф|журнал регистрации|тех процесс|технологическ", k):
        return ("Нерелевантно", "Прочие запросы вне тематики", "—", "")
    rel = "Нецелевой сегмент (школы, общепит, вода и т. п.)" if has(NONTARGET_SEG, k) else ("Целевой" if not topic.startswith("99") else "Проверить вручную")
    flag = "Частота завышена: короткая маска со стоп-словом («ту»/«то»), нужна фразовая частота" if (has(r"\bту\b", k) and len(k.split()) <= 2) else ""
    return (rel, topic, intent, flag)

res = []
for k, f in rows:
    rel, topic, intent, flag = classify(k)
    cluster = f"{topic} · {intent}" if rel not in ("Нерелевантно",) else f"Шум · {topic}"
    res.append(dict(keyword=k, frequency=f, relevance=rel, topic=topic, intent=intent, cluster=cluster,
                    page=PAGE.get(topic, "") if rel == "Целевой" else "", note=flag))

res.sort(key=lambda r: (r["relevance"] != "Целевой", r["topic"], r["intent"], -r["frequency"]))
with open(f"{out}/wordstat-clustered.csv", "w", newline="", encoding="utf-8") as fh:
    w = csv.DictWriter(fh, fieldnames=["keyword", "frequency", "relevance", "topic", "intent", "cluster", "page", "note"])
    w.writeheader(); w.writerows(res)

# Сводки (без суммирования частот: head = максимальная частота в группе)
def head(items): 
    it = max(items, key=lambda r: r["frequency"]); return it["keyword"], it["frequency"]
by_rel = defaultdict(list)
for r in res: by_rel[r["relevance"]].append(r)
print("== Релевантность (число фраз; head-фраза)")
for k, v in sorted(by_rel.items(), key=lambda x: -len(x[1])): print(f"  {k}: {len(v)} фраз; head {head(v)}")
noise = defaultdict(list)
for r in res:
    if r["relevance"] == "Нерелевантно": noise[r["topic"]].append(r)
print("== Шум по причинам")
for k, v in sorted(noise.items(), key=lambda x: -len(x[1])): print(f"  {k}: {len(v)}; head {head(v)}")
tgt = [r for r in res if r["relevance"] == "Целевой" and not r["note"]]
by_t = defaultdict(list)
for r in tgt: by_t[r["topic"]].append(r)
print("== Целевые темы: фраз | head | коммерческих фраз | макс. коммерческая")
for t in sorted(by_t):
    v = by_t[t]; com = [r for r in v if r["intent"].startswith("Коммерческий")]
    hc = head(com) if com else ("—", 0)
    print(f"  {t}: {len(v)} | {head(v)} | {len(com)} | {hc}")
clusters = defaultdict(list)
for r in tgt: clusters[r["cluster"]].append(r)
with open(f"{out}/clusters-summary.csv", "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh); w.writerow(["cluster", "topic", "intent", "phrases", "head_keyword", "head_frequency", "top_phrases", "page"])
    for c, v in sorted(clusters.items(), key=lambda x: -head(x[1])[1]):
        hk, hf = head(v); top = "; ".join(f"{r['keyword']} ({r['frequency']})" for r in sorted(v, key=lambda r: -r["frequency"])[:8])
        w.writerow([c, v[0]["topic"], v[0]["intent"], len(v), hk, hf, top, v[0]["page"]])
print("clusters:", len(clusters))
